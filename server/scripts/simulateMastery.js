// Phase 2 simulation: does the BKT recover KNOWN mastery? (no AI calls, no database, seeded)
// Usage: npm run sim:mastery            (options: --n 3000 --sessions 8 --range-subset 150)
//
// Synthetic student × skill trajectories:
//  - a resume status (missing / partial / matched, ⅓ each) and a TRUE starting mastery drawn from
//    the scenario's true prior for that status
//  - one question on the skill per interview; results are always viewed, so between interviews a
//    not-mastered student truly learns with the scenario's learn rate
//  - answer quality ~ the scenario's TRUE score curves (true uniform part 5 %, scenario F 15 %);
//    observed score = quality + scorer noise (sd 3 points + 20 × (1 − confidence));
//    confidence ~ 85 % in [0.85, 1], 15 % in [0.5, 0.85]
// The model uses the app's settings (config/mastery.js) and is run with TWO uniform parts —
// 5 % and 15 % — on the SAME simulated answers, so the comparison is fair. Scenarios B–F make the
// model's assumptions wrong on purpose, to see how robust each setting is.
//
// CAVEAT: students are generated by the same KIND of model being tested, so this checks the
// implementation and its sensitivity to wrong parameters — not that real students behave this way.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { traceSkill, masteryRange, curvesFor, seededRandom } from '../src/services/mastery/bkt.js';
import { PARAMS, PRIORS, CURVES, RANGE } from '../src/config/mastery.js';
import { mean } from '../src/utils/stats.js';

const args = process.argv.slice(2);
const opt = (name, def) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? Number(args[i + 1]) : def;
};
const N = opt('n', 3000); // trajectories per scenario
const SESSIONS = opt('sessions', 8);
const RANGE_SUBSET = opt('range-subset', 150); // trajectories used for the (slower) range-coverage check
const THRESHOLDS = [0.85, 0.9, 0.95];
const STATUSES = ['missing', 'partial', 'matched'];
const MODEL_EPS = [0.05, 0.15]; // the two settings compared

const BASE = { priors: { ...PRIORS }, learn: PARAMS.learn, guess: PARAMS.guess, slip: PARAMS.slip, noiseScale: 1, trueEps: 0.05 };
const SCENARIOS = [
  { id: 'A', name: 'model assumptions correct', ...BASE },
  { id: 'B', name: 'noisier students (guess 0.30, slip 0.15)', ...BASE, guess: 0.3, slip: 0.15 },
  { id: 'C1', name: 'faster learners (learn 0.25)', ...BASE, learn: 0.25 },
  { id: 'C2', name: 'slower learners (learn 0.03)', ...BASE, learn: 0.03 },
  { id: 'D', name: 'resumes over-claim (true prior matched 0.35, partial 0.20)', ...BASE, priors: { ...PRIORS, matched: 0.35, partial: 0.2 } },
  { id: 'E', name: 'noisier scoring (2× scorer noise)', ...BASE, noiseScale: 2 },
  { id: 'F', name: 'messier real scores (15 % random outcomes)', ...BASE, trueEps: 0.15 },
];

// ---------- sampling helpers (exact inverse-CDF draws for the one-sided Beta curves) ----------
function sampleCurve(c, rnd) {
  if (rnd() < c.eps) return rnd(); // the uniform part
  return c.b === 1 ? rnd() ** (1 / c.a) : 1 - rnd() ** (1 / c.b); // Beta(a,1) or Beta(1,b)
}
function gaussian(rnd) {
  const u = Math.max(rnd(), 1e-12);
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * rnd());
}

/** Simulated answers + true states. Model traces are added afterwards, per model setting. */
function simulate(sc, seed) {
  const rnd = seededRandom(seed);
  const trueCurveSettings = { ...CURVES, eps: sc.trueEps };
  const trueCurves = curvesFor({ guess: sc.guess, slip: sc.slip }, trueCurveSettings);
  const trueParams = { learn: sc.learn, guess: sc.guess, slip: sc.slip, forget: 0 };
  const trajectories = [];
  for (let i = 0; i < N; i++) {
    const status = STATUSES[i % 3];
    let mastered = rnd() < sc.priors[status];
    const evidence = [];
    const truth = [];
    for (let s = 0; s < SESSIONS; s++) {
      if (s > 0 && !mastered && rnd() < sc.learn) mastered = true;
      const confidence = rnd() < 0.85 ? 0.85 + 0.15 * rnd() : 0.5 + 0.35 * rnd();
      const quality = sampleCurve(mastered ? trueCurves.mastered : trueCurves.notMastered, rnd);
      const noise = gaussian(rnd) * (3 + 20 * (1 - confidence)) * sc.noiseScale;
      const score = Math.round(Math.min(100, Math.max(0, 100 * quality + noise)));
      evidence.push({ score, weight: confidence, learnBefore: s > 0 });
      truth.push(mastered);
    }
    const t = { status, evidence, truth };
    t.threshold = traceSkill(PRIORS[status], evidence, { model: 'threshold' }).steps.map((x) => x.pAfter);
    // oracle = the same update with the TRUE parameters and TRUE curves
    t.oracle = traceSkill(sc.priors[status], evidence, { params: trueParams, curves: trueCurveSettings }).steps.map((x) => x.pAfter);
    for (const eps of MODEL_EPS) {
      t[`m${eps}`] = traceSkill(PRIORS[status], evidence, { curves: { ...CURVES, eps } }).steps.map((x) => x.pAfter);
    }
    trajectories.push(t);
  }
  return trajectories;
}

// ---------- metrics ----------
function brier(tr, key) {
  return mean(tr.flatMap((t) => t[key].map((p, i) => (p - (t.truth[i] ? 1 : 0)) ** 2)));
}

/** Expected calibration error over 10 equal-width bins, plus the bins themselves */
function calibration(tr, key) {
  const bins = Array.from({ length: 10 }, () => ({ n: 0, p: 0, y: 0 }));
  for (const t of tr) {
    t[key].forEach((p, i) => {
      const b = bins[Math.min(9, Math.floor(p * 10))];
      b.n++;
      b.p += p;
      b.y += t.truth[i] ? 1 : 0;
    });
  }
  const total = bins.reduce((s, b) => s + b.n, 0);
  const ece = bins.reduce((s, b) => s + (b.n ? (b.n / total) * Math.abs(b.p / b.n - b.y / b.n) : 0), 0);
  return { ece, bins: bins.map((b, i) => ({ bin: `${i * 10}-${i * 10 + 10}%`, n: b.n, predicted: b.n ? b.p / b.n : null, actual: b.n ? b.y / b.n : null })) };
}

const quantile = (xs, q) => {
  if (!xs.length) return null;
  const v = [...xs].sort((a, b) => a - b);
  return v[Math.min(v.length - 1, Math.floor(q * (v.length - 1) + 0.5))];
};

/** Mastery decisions at threshold t: the first answer after which P ≥ t is the "declaration" */
function decisions(tr, key, t) {
  let declared = 0, falseMastery = 0, masteredFromStart = 0, reachedFromStart = 0;
  const answersNeeded = []; // for students mastered from the start
  const delays = []; // for students who learned mid-way: answers between true mastery and declaration
  for (const tj of tr) {
    const i = tj[key].findIndex((p) => p >= t);
    if (i >= 0) {
      declared++;
      if (!tj.truth[i]) falseMastery++;
    }
    if (tj.truth[0]) {
      masteredFromStart++;
      if (i >= 0) {
        reachedFromStart++;
        answersNeeded.push(i + 1);
      }
    } else {
      const learnedAt = tj.truth.indexOf(true);
      if (learnedAt > 0 && i >= learnedAt) delays.push(i - learnedAt + 1);
    }
  }
  return {
    threshold: t,
    falseMasteryRate: declared ? falseMastery / declared : 0,
    declared,
    answersNeededMedian: quantile(answersNeeded, 0.5),
    answersNeededP90: quantile(answersNeeded, 0.9),
    reachedWithinSessions: masteredFromStart ? reachedFromStart / masteredFromStart : 0,
    delayAfterLearningMedian: quantile(delays, 0.5),
  };
}

/** How often the shown range contains the oracle's P (the P we'd compute with the TRUE parameters) */
function rangeCoverage(tr, eps) {
  let inside = 0, total = 0;
  const widths = [];
  for (const t of tr.slice(0, RANGE_SUBSET)) {
    for (let i = 0; i < t.evidence.length; i++) {
      const r = masteryRange(PRIORS[t.status], t.evidence.slice(0, i + 1), { seed: `sim|${i}`, curves: { ...CURVES, eps } });
      total++;
      widths.push(r.high - r.low);
      if (t.oracle[i] >= r.low - 1e-9 && t.oracle[i] <= r.high + 1e-9) inside++;
    }
  }
  return { coverage: inside / total, meanWidth: mean(widths) };
}

// ---------- run ----------
const results = [];
const t0 = Date.now();
for (const sc of SCENARIOS) {
  const tr = simulate(sc, `scenario-${sc.id}`);
  const row = { id: sc.id, name: sc.name, oracleBrier: brier(tr, 'oracle'), threshold: { brier: brier(tr, 'threshold'), ece: calibration(tr, 'threshold').ece } };
  for (const eps of MODEL_EPS) {
    const key = `m${eps}`;
    row[key] = {
      brier: brier(tr, key),
      ece: calibration(tr, key).ece,
      calibrationBins: calibration(tr, key).bins,
      decisions: THRESHOLDS.map((t) => decisions(tr, key, t)),
      range: rangeCoverage(tr, eps),
    };
  }
  results.push(row);
}

// ---------- report ----------
const f = (x, d = 3) => (x == null ? '  – ' : x.toFixed(d));
const p = (x) => (x == null ? ' – ' : `${Math.round(x * 100)}%`.padStart(4));
const at95 = (m) => m.decisions.find((d) => d.threshold === 0.95);
console.log(`BKT simulation: ${N} student×skill trajectories per scenario, ${SESSIONS} interviews, 1 question each; model uniform part ${MODEL_EPS.map((e) => e * 100 + ' %').join(' vs ')} (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
console.log(`Sampled parameter ranges: prior ×${RANGE.priorFactor.join('–')}, learn ${RANGE.learn.join('–')}, guess ${RANGE.guess.join('–')}, slip ${RANGE.slip.join('–')}`);
console.log('Brier: 0 = perfect, lower is better. ECE = calibration error. Coverage = how often the shown range contains');
console.log('the P computed with the TRUE parameters. Needed = answers to reach 95 % (students mastered from the start).');
console.log('False = share of "mastered at 95 %" declarations made while the student was NOT mastered.\n');
console.log('  scenario                                      uniform  Brier   ECE    coverage  width   needed→95% (90th)  false@95%');
for (const r of results) {
  MODEL_EPS.forEach((eps, j) => {
    const m = r[`m${eps}`];
    const d = at95(m);
    console.log(
      `  ${(j === 0 ? `${r.id} ${r.name}` : '').padEnd(46).slice(0, 46)}  ${(eps * 100 + ' %').padStart(5)}   ${f(m.brier)}  ${f(m.ece)}   ${p(m.range.coverage)}    ${f(m.range.meanWidth, 2)}    ${String(d.answersNeededMedian ?? '–').padStart(2)} (${d.answersNeededP90 ?? '–'})            ${p(d.falseMasteryRate)}`
    );
  });
  console.log(`  ${''.padEnd(46)}  thr.     ${f(r.threshold.brier)}  ${f(r.threshold.ece)}   (oracle Brier ${f(r.oracleBrier)})`);
}

console.log('\nAll thresholds, per setting (needed median / 90th pct · false mastery):');
for (const r of results) {
  for (const eps of MODEL_EPS) {
    const ds = r[`m${eps}`].decisions.map((d) => `≥${Math.round(d.threshold * 100)}%: ${d.answersNeededMedian}/${d.answersNeededP90} · ${p(d.falseMasteryRate)}`).join('   ');
    console.log(`  ${r.id.padEnd(3)} ${(eps * 100 + ' %').padStart(5)}   ${ds}`);
  }
}

console.log('\nCalibration, scenario A, uniform 15 %: predicted vs actual share mastered per bin');
for (const b of results[0]['m0.15'].calibrationBins) if (b.n) console.log(`  ${b.bin.padEnd(8)} n=${String(b.n).padStart(5)}  predicted ${f(b.predicted, 2)}  actual ${f(b.actual, 2)}`);

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'eval', 'mastery', 'results');
fs.mkdirSync(dir, { recursive: true });
const out = path.join(dir, `sim-${new Date().toISOString().slice(0, 10)}.json`);
fs.writeFileSync(out, JSON.stringify({ settings: { N, SESSIONS, THRESHOLDS, MODEL_EPS, model: { PARAMS, PRIORS, RANGE } }, results }, null, 2));
console.log(`\nSaved ${path.relative(process.cwd(), out)}`);
